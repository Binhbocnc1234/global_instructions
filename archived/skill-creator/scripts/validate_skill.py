#!/usr/bin/env python3
"""Validate the structure of an agent skill folder against house rules.

Checks performed:
    1. SKILL.md exists in the skill folder.
    2. Frontmatter is present, delimited by `---` lines, and parses as
       simple key: value pairs.
    3. `name` and `description` are present and non-empty.
    4. `name` matches ^[a-z0-9]+(-[a-z0-9]+)*$ and is 1 to 64 characters.
    5. `name` equals the folder name.
    6. `description` is at most 1024 characters.
    7. Every .md file in the skill folder tree is at most 250 lines.
    8. No supporting file sits more than one directory below the skill root.
    9. No unfilled scaffold placeholders remain (TODO, FIXME, XXX, or an
       angle-bracket placeholder like <name>), outside fenced code blocks.
    10. Every relative Markdown link in SKILL.md resolves to a file that
        actually exists.

What this script does NOT check: whether the skill's instructions are good,
whether the description actually routes correctly, or whether the skill
makes good decisions. Those need the discovery check and behavior check
described in SKILL.md, not this script. This script checks structure only.
"""

import re
import sys
from pathlib import Path

MAX_MD_LINES = 250
MAX_NAME_LEN = 64
MAX_DESC_LEN = 1024
NAME_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
PLACEHOLDER_RE = re.compile(r"TODO|FIXME|XXX|<[a-z-]+>")
MD_LINK_RE = re.compile(r"\[[^\]]*\]\(([^)]+)\)")
INLINE_CODE_RE = re.compile(r"`[^`]*`")
# Generated by tooling, not authored content, so never reported.
IGNORED_DIRS = {"__pycache__", ".git", "node_modules", ".venv"}


def is_ignored(path, skill_dir):
    return any(part in IGNORED_DIRS for part in path.relative_to(skill_dir).parts)


class Issue:
    """One reported problem: where it was found, which check, and why."""

    def __init__(self, path, check, message):
        self.path = path
        self.check = check
        self.message = message

    def __str__(self):
        return f"{self.path}: {self.check}: {self.message}"


def parse_frontmatter(text):
    """Parse a leading `---` delimited block of plain key: value pairs.

    Returns (dict, remainder_text). Returns (None, text) when no valid
    frontmatter block is found. Does not require PyYAML: only plain
    scalars and quoted strings are supported, which is all SKILL.md needs.
    """
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None, text
    end_idx = None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            end_idx = i
            break
    if end_idx is None:
        return None, text
    data = {}
    for line in lines[1:end_idx]:
        if not line.strip() or line.strip().startswith("#") or ":" not in line:
            continue
        key, _, value = line.partition(":")
        key = key.strip()
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in ("'", '"'):
            value = value[1:-1]
        data[key] = value
    remainder = "\n".join(lines[end_idx + 1:])
    return data, remainder


def check_skill_md_exists(skill_dir, issues):
    """Check 1: SKILL.md exists. Returns its Path, or None if missing."""
    skill_md = skill_dir / "SKILL.md"
    if not skill_md.is_file():
        issues.append(Issue("SKILL.md", "existence", "SKILL.md not found in skill folder"))
        return None
    return skill_md


def check_frontmatter(skill_md, issues):
    """Checks 2: frontmatter block exists and parses. Returns the parsed dict."""
    text = skill_md.read_text(encoding="utf-8")
    data, _ = parse_frontmatter(text)
    if data is None:
        issues.append(Issue("SKILL.md", "frontmatter", "no valid frontmatter block delimited by --- lines"))
        return {}
    return data


def check_name_and_description(data, skill_dir, issues):
    """Checks 3, 4, 5, 6: name and description presence, format, and match."""
    name = data.get("name", "")
    description = data.get("description", "")

    if not name:
        issues.append(Issue("SKILL.md", "name", "frontmatter 'name' is missing or empty"))
    if not description:
        issues.append(Issue("SKILL.md", "description", "frontmatter 'description' is missing or empty"))

    if name:
        if not NAME_RE.match(name) or not (1 <= len(name) <= MAX_NAME_LEN):
            issues.append(Issue(
                "SKILL.md", "name-format",
                f"'{name}' must match ^[a-z0-9]+(-[a-z0-9]+)*$ and be 1 to {MAX_NAME_LEN} characters"))
        folder_name = skill_dir.name
        if name != folder_name:
            issues.append(Issue(
                "SKILL.md", "name-folder-match",
                f"frontmatter name '{name}' does not match folder name '{folder_name}'"))

    if description and len(description) > MAX_DESC_LEN:
        issues.append(Issue(
            "SKILL.md", "description-length",
            f"description is {len(description)} characters, must be at most {MAX_DESC_LEN}"))


def check_markdown_lengths(skill_dir, issues):
    """Check 7: every .md file is at most MAX_MD_LINES lines."""
    for md_file in sorted(skill_dir.rglob("*.md")):
        if is_ignored(md_file, skill_dir):
            continue
        rel = md_file.relative_to(skill_dir)
        line_count = len(md_file.read_text(encoding="utf-8").splitlines())
        if line_count > MAX_MD_LINES:
            issues.append(Issue(
                str(rel), "file-length",
                f"{line_count} lines, must be at most {MAX_MD_LINES}"))


def check_directory_depth(skill_dir, issues):
    """Check 8: no file sits more than one directory below the skill root."""
    for path in sorted(skill_dir.rglob("*")):
        if is_ignored(path, skill_dir):
            continue
        if path.is_file():
            rel = path.relative_to(skill_dir)
            depth = len(rel.parts) - 1
            if depth > 1:
                issues.append(Issue(
                    str(rel), "directory-depth",
                    f"file is {depth} directories below the skill root, must be at most 1"))


def check_placeholders(skill_dir, issues):
    """Check 9: no unfilled scaffold placeholder remains outside fenced code blocks."""
    for md_file in sorted(skill_dir.rglob("*.md")):
        if is_ignored(md_file, skill_dir):
            continue
        rel = md_file.relative_to(skill_dir)
        in_fence = False
        for lineno, line in enumerate(md_file.read_text(encoding="utf-8").splitlines(), start=1):
            if line.strip().startswith("```"):
                in_fence = not in_fence
                continue
            if in_fence:
                continue
            # Angle-bracket notation inside an inline code span is template
            # syntax, such as `<type>(<scope>): <subject>`, not scaffolding.
            scannable = INLINE_CODE_RE.sub("", line)
            for match in PLACEHOLDER_RE.finditer(scannable):
                issues.append(Issue(
                    str(rel), "placeholder",
                    f"line {lineno}: unfilled placeholder '{match.group(0)}'"))


def check_links(skill_md, issues):
    """Check 10: every relative Markdown link in SKILL.md resolves to a real file."""
    # A link inside a fenced block is illustration, not a real reference.
    lines = []
    in_fence = False
    for line in skill_md.read_text(encoding="utf-8").splitlines():
        if line.strip().startswith("```"):
            in_fence = not in_fence
            continue
        if not in_fence:
            lines.append(line)
    text = "\n".join(lines)
    for match in MD_LINK_RE.finditer(text):
        target = match.group(1).strip()
        if target.startswith(("http://", "https://", "#", "mailto:")):
            continue
        path_part = target.split("#", 1)[0]
        if not path_part:
            continue
        resolved = (skill_md.parent / path_part).resolve()
        if not resolved.is_file():
            issues.append(Issue(
                "SKILL.md", "link",
                f"link target '{target}' does not resolve to an existing file"))


def validate_skill(skill_dir):
    """Run every check against skill_dir. Returns the list of Issue objects."""
    issues = []
    skill_md = check_skill_md_exists(skill_dir, issues)
    if skill_md is None:
        return issues
    data = check_frontmatter(skill_md, issues)
    check_name_and_description(data, skill_dir, issues)
    check_markdown_lengths(skill_dir, issues)
    check_directory_depth(skill_dir, issues)
    check_placeholders(skill_dir, issues)
    check_links(skill_md, issues)
    return issues


def main():
    if len(sys.argv) != 2:
        print("usage: python validate_skill.py <path-to-skill-folder>")
        return 2
    skill_dir = Path(sys.argv[1]).resolve()
    if not skill_dir.is_dir():
        print(f"{skill_dir}: not a directory")
        return 2

    issues = validate_skill(skill_dir)
    for issue in issues:
        print(issue)

    if issues:
        print(f"{len(issues)} issue(s) found")
        return 1

    print("SKILL.md and its supporting files pass all structural checks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
